#: (days ago when it started, model). The last entry whose start >= d applies on day d.
TIMELINE: dict[str, list[tuple[int, str]]] = {
    "returns-assistant": [(60, "sim/model-a"), (12, "sim/model-c")],
    "it-helpdesk": [(60, "sim/model-c"), (6, "sim/model-b"), (3, "sim/model-c")],
    "loyalty-concierge": [(60, "sim/model-c"), (20, "sim/model-a")],
}


def model_on(agent: str, days_ago: int, default: str) -> str:
    chosen = default
    for start, model in TIMELINE.get(agent, [(60, default)]):
        if days_ago <= start:
            chosen = model
    return chosen


def changes(agent: str, default: str) -> list[tuple[int, str, str]]:
    """(day the change took effect, old model, new model)."""
    events = TIMELINE.get(agent, [])
    return [(events[i][0], events[i - 1][1], events[i][1]) for i in range(1, len(events))]


def stamp(run: Run, when: datetime, **labels: str) -> Run:
    run.created_at = when
    run.finished_at = when + timedelta(seconds=45)
    run.labels = {**run.labels, "seeded": "true", **labels}
    return run


# --- span re-timing --------------------------------------------------------------------------

DEFAULT_MS = {"execute_tool": 45.0, "retrieval": 18.0}


def retime(spans: list[SpanRecord], start_ns: int) -> None:
    """Re-lay a trace on a realistic timeline: model calls last as long as the model's *simulated* latency."""
    ids = {s.span_id for s in spans}
    children: dict[str | None, list[SpanRecord]] = defaultdict(list)
    for s in sorted(spans, key=lambda s: s.start_time_ns):
        parent = s.parent_span_id if s.parent_span_id in ids else None
        children[parent].append(s)

    def intrinsic_ms(s: SpanRecord) -> float:
        if "pground.latency_ms" in s.attributes:
            return float(s.attributes["pground.latency_ms"])
        op = s.attributes.get("gen_ai.operation.name") or s.name
        return DEFAULT_MS.get(str(op), 30.0 if s.status == "error" else 1.0)

    def place(span: SpanRecord, begin: int) -> int:
        cursor = begin + 500_000
        kids = children.get(span.span_id, [])
        for kid in kids:
            cursor = place(kid, cursor)
        end = cursor + 500_000 if kids else begin + int(intrinsic_ms(span) * 1e6)
        shift = begin - span.start_time_ns
        span.events = [{**e, "time_ns": e.get("time_ns", 0) + shift} for e in span.events]
        span.start_time_ns, span.end_time_ns = begin, end
        return end

    cursor = start_ns
    for root in children.get(None, []):
        cursor = place(root, cursor)


# --- phases ----------------------------------------------------------------------------------


async def history(cfg, days: int, sample: int, rng: random.Random) -> int:  # type: ignore[no-untyped-def]
    specs = load_specs(root=str(ROOT))
    now = datetime.now(UTC)
    n_runs = 0
    for slug, spec in sorted(specs.items()):
        if not spec.suites:
            continue
        started = time.monotonic()
        for d in range(days - 1, -1, -1):
            when = (now - timedelta(days=d)).replace(
                hour=3, minute=rng.randint(0, 40), second=rng.randint(0, 59)
            )
            model = model_on(slug, d, spec.model)
            settings = settings_from_config(cfg, sample=sample, seed=d + 1, use_cache=False, n_boot=300)
            run = await run_target(
                cfg, slug, settings=settings, overrides={"model": model}, labels={"kind": "eval"}
            )
            async with session_scope() as session:
                await store.save_run(session, stamp(run, when, ref="main"), store_spans=False)
            n_runs += 1
        print(f"  {slug:22s} {days} nightly runs  ({time.monotonic() - started:.1f}s)")
    return n_runs


async def gate_events(cfg, days: int) -> None:  # type: ignore[no-untyped-def]
    specs = load_specs(root=str(ROOT))
    now = datetime.now(UTC)
    for slug, spec in sorted(specs.items()):
        for day, old, new in changes(slug, spec.model):
            if day > days:
                continue
            when = (now - timedelta(days=day)).replace(hour=14, minute=10, second=0)
            settings = settings_from_config(
                cfg, seed=7, use_cache=False, n_boot=500
            )  # full suites: enough power
            result, _comparison, candidate, baseline = await gate_target(
                cfg,
                slug,
                "release",
                settings=settings,
                candidate_overrides={"model": new},
                baseline_overrides={"model": old},
            )
            assert baseline is not None
            async with session_scope() as session:
                await store.save_run(
                    session, stamp(baseline, when - timedelta(minutes=9), role="baseline"), store_spans=False
                )
                await store.save_run(
                    session,
                    stamp(candidate, when - timedelta(minutes=2), role="candidate"),
                    store_spans=False,
                )
                await record_gate(session, result, when)
            print(
                f"  gate  {slug:20s} day -{day:<2d} {old.split('/')[-1]} -> {new.split('/')[-1]}: {result.verdict}"
            )


async def redteam_runs(cfg, days: int) -> None:  # type: ignore[no-untyped-def]
    specs = load_specs(root=str(ROOT))
    now = datetime.now(UTC)
    count = 0
    for slug, spec in sorted(specs.items()):
        suites = [s for s in spec.suites if s.startswith("security-")]
        if not suites:
            continue
        for d in range(days - 1, -1, -7):
            when = (now - timedelta(days=d)).replace(hour=4, minute=30, second=0)
            model = model_on(slug, d, spec.model)
            settings = settings_from_config(cfg, use_cache=False, n_boot=200)
            run = await run_target(
                cfg,
                slug,
                suites=suites,
                settings=settings,
                overrides={"model": model},
                labels={"kind": "redteam"},
            )
            async with session_scope() as session:
                await store.save_run(session, stamp(run, when, ref="main"), store_spans=False)
            count += 1
    print(f"  {count} weekly red-team campaigns")


def diurnal(hour: int) -> float:
    return 0.35 + 0.65 * max(0.0, math.sin((hour - 6) / 12 * math.pi))


async def traffic_history(cfg, hours: int, rng: random.Random, scale: float) -> int:  # type: ignore[no-untyped-def]
    setup_tracing(service_name="acme-agents")  # in-process collector only: no OTLP while seeding
    specs = load_specs(root=str(ROOT))
    pools = load_pools(cfg)
    tracer = get_tracer("seed")
    agents = {
        slug: Agent(spec.model_copy(update={"model": model_on(slug, 0, spec.model)}))
        for slug, spec in specs.items()
        if slug in WEIGHTS
    }
    now = datetime.now(UTC)
    total = 0
    for slug, agent in agents.items():
        normal, attacks = pools.get(slug, ([], []))
        if not normal:
            continue
        for h in range(hours, 0, -1):
            slot = now - timedelta(hours=h)
            n = max(0, round(WEIGHTS[slug] * 5 * scale * diurnal(slot.hour) * rng.uniform(0.7, 1.3)))
            for _ in range(n):
                case = rng.choice(attacks) if attacks and rng.random() < 0.04 else rng.choice(normal)
                begin = slot + timedelta(seconds=rng.uniform(0, 3599))
                # A wrapper span gives every request a trace id, even when the agent raises (simulated upstream error).
                with tracer.start_as_current_span("seed.request") as wrapper:
                    trace_id = format(wrapper.get_span_context().trace_id, "032x")
                    wrapper_id = format(wrapper.get_span_context().span_id, "016x")
                    with contextlib.suppress(Exception):
                        await agent.run(
                            AgentRequest(input=case.input, messages=case.messages, context=case.context)
                        )
                spans = [sp for sp in collector.pop(trace_id) if sp.name != "seed.request"]
                for sp in spans:
                    if sp.parent_span_id == wrapper_id:
                        sp.parent_span_id = None
                if not spans:
                    continue
                retime(spans, int(begin.timestamp() * 1e9))
                async with session_scope() as session:
                    await ingest_spans(session, spans)
                total += 1
    return total


async def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--days", type=int, default=30)
    parser.add_argument("--sample", type=int, default=14, help="cases per suite per nightly run")
    parser.add_argument("--traffic-hours", type=int, default=24)
    parser.add_argument("--traffic-scale", type=float, default=1.0)
    parser.add_argument(
        "--reset", action="store_true", help="delete existing runs, traces and gate history first"
    )
    parser.add_argument("--seed", type=int, default=2026)
    args = parser.parse_args()

    cfg = load_config(ROOT / "provingground.yaml")
    rng = random.Random(args.seed)
    init_engine()
    try:
        if args.reset:
            async with session_scope() as session:
                await session.execute(
                    text(
                        "truncate runs, case_results, scores, spans, gate_evaluations, comparisons, online_scores, jobs restart identity cascade"
                    )
                )
            print("reset: cleared runs, traces, gate history")
        async with session_scope() as session:
            print("synced from config:", await sync_config(session))
        print(f"\n[1/4] nightly evaluation history ({args.days} days x 20 agents)")
        n = await history(cfg, args.days, args.sample, rng)
        print("\n[2/4] model changes through the release gate")
        await gate_events(cfg, args.days)
        print("\n[3/4] red-team campaigns")
        await redteam_runs(cfg, args.days)
        print(f"\n[4/4] production traffic ({args.traffic_hours}h)")
        traces = await traffic_history(cfg, args.traffic_hours, rng, args.traffic_scale)
        print(f"  {traces} traces replayed")
        print(f"\nseeded {n} nightly runs, gate history, red-team campaigns and {traces} traces.")
    finally:
        await dispose_engine()


if __name__ == "__main__":
    asyncio.run(main())
