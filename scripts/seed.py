"""Seed the platform with a believable fleet history.

    uv run python scripts/seed.py [--days 30] [--traffic-hours 24] [--reset]

Everything is *generated by really running the demo agents* (on the simulated models), then
time-shifted into the past - nothing is hand-written. The story it tells:

* every agent is evaluated nightly for ``--days`` days (sampled suites; scores move with the
  sample, not randomly);
* ``returns-assistant`` moves from model A to the cheaper model C (gate PASS, cost drops);
* ``it-helpdesk`` is moved to the budget model B (gate FAIL, quality and safety regress) and is
  rolled back three days later;
* ``loyalty-concierge`` is upgraded to model A;
* ``store-info-bot`` and ``review-summarizer`` run on the budget model all along, so they show
  up as the fleet's weak spots;
* weekly red-team campaigns for the agents with security suites;
* ``--traffic-hours`` of production traces (diurnal curve) replayed into the trace store.
"""

